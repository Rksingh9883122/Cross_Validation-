import numpy as np
import pandas as pd
from sklearn.model_selection import train_test_split
from sklearn.model_selection import cross_val_score
from sklearn.metrics import accuracy_score, classification_report
import matplotlib.pyplot as plt

# Importing the models

from sklearn.svm import SVC

from sklearn.ensemble import RandomForestClassifier
from sklearn.neighbors import KNeighborsClassifier
from sklearn.linear_model import LogisticRegression

df = pd.read_csv("/content/sample_data/heart.csv")
df.head
X = df.drop(columns = "target", axis = 1)
y = df['target']

X_train, X_test, y_train, y_test = train_test_split(X, y, test_size=.30, stratify = y, random_state=42) ## Startify ensure same number of data in both x & y

models = [LogisticRegression(), SVC(kernel='linear'), KNeighborsClassifier(), RandomForestClassifier()]

def compare_model():
    for model in models:
        model.fit(X_train, y_train) # Indented this line
        y_pred = model.predict(X_test) # Indented this line
        accuracy = accuracy_score(y_test, y_pred) # Indented this line
        print("Accuracy of the", model, "= ", accuracy) # Indented this line and corrected the print statement

compare_model()

