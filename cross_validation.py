def compare_model():
    for model in models:
        cross_val_score_model = cross_val_score(model, X, y, cv=5) # Indented these lines and corrected the model input
        print(cross_val_score_model) # Indented these lines
        mean = np.mean(cross_val_score_model) # Indented these lines
        print(mean) # Indented these lines
        print("mean:",round(mean)) # Indented these lines

        print("model_name:", model)
        print("cross_validation_score:",cross_val_score_model)
        print("mean:",round(mean))

compare_model()

